"""Write the licence texts of the npm packages bundled into the dashboard.

The production build minifies React, react-router, TanStack Query, Lucide and the IBM Plex fonts into
``src/kestrix/server/static/``, which ships in the ``kestrix`` wheel; their MIT, ISC and OFL-1.1 licences
require the notice to travel with them. This script follows ``frontend/package.json`` ``dependencies``
through ``frontend/node_modules`` and writes ``frontend/public/THIRD_PARTY_LICENSES.txt``, which Vite
copies into the build. Type-only packages (``@types/*`` and what only they need) are not bundled and are left out.

Run from the repo root after ``npm --prefix frontend ci``: ``python3 scripts/build_third_party_licenses.py``.
With ``--check`` it writes nothing and exits 1 when the committed file is out of date (CI runs that).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

FRONTEND = Path(__file__).resolve().parents[1] / "frontend"
MODULES = FRONTEND / "node_modules"
OUT = FRONTEND / "public" / "THIRD_PARTY_LICENSES.txt"
LICENSE_NAMES = ("LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "COPYING")


def manifest(name: str) -> dict[str, object]:
    path = MODULES / name / "package.json"
    if not path.is_file():
        raise SystemExit(f"{path} is missing; run npm --prefix frontend ci first")
    data: dict[str, object] = json.loads(path.read_text(encoding="utf-8"))
    return data


def bundled() -> list[str]:
    """Runtime dependencies and theirs, without type-only packages, sorted by name."""
    root = json.loads((FRONTEND / "package.json").read_text(encoding="utf-8"))
    todo = [name for name in root.get("dependencies", {}) if not name.startswith("@types/")]
    seen: set[str] = set()
    while todo:
        name = todo.pop()
        if name in seen:
            continue
        seen.add(name)
        deps = manifest(name).get("dependencies") or {}
        assert isinstance(deps, dict)
        todo += [dep for dep in deps if not dep.startswith("@types/")]
    return sorted(seen)


def render() -> str:
    parts = [
        "Third-party software bundled into the Kestrix dashboard",
        "",
        "Generated by scripts/build_third_party_licenses.py from frontend/node_modules; do not edit.",
        "Kestrix itself is Apache-2.0; see LICENSE and NOTICE in the repository.",
    ]
    for name in bundled():
        data = manifest(name)
        text = next(
            (
                (MODULES / name / file).read_text(encoding="utf-8")
                for file in LICENSE_NAMES
                if (MODULES / name / file).is_file()
            ),
            None,
        )
        if text is None:
            raise SystemExit(f"{name} ships no licence file; add its licence text by hand before bundling it")
        parts += ["", "=" * 78, f"{name} {data.get('version')} ({data.get('license')})", "=" * 78, "", text.strip()]
    return "\n".join(parts) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date; run scripts/build_third_party_licenses.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
