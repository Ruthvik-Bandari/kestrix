"""Generate the landing page's "with Kestrix" samples from REAL Kestrix output.

Run from the repo root: ``uv run python scripts/build_landing_samples.py``. Every input is
synthetic and built here (reserved ``.example`` domains, documentation IP ranges, a fictional
bank ``northbank.example``); every verdict, finding, count and grade in the output comes from
running the Kestrix functions on those inputs. Output goes to
``frontend/src/features/landing/samples/*.json`` and is committed, so the landing page can
show it offline. ``tests/test_landing_samples.py`` re-runs the offline generators and fails if
the committed JSON drifts from what the code produces.

The webcheck sample starts a throwaway HTTP server on 127.0.0.1 and fails loudly instead of
writing invented data.
"""

from __future__ import annotations

import json
import sys
import threading
from email.message import EmailMessage
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import Any

from kestrix.mail.analyze import analyze as analyze_mail
from kestrix.webcheck.scan import scan as scan_site

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "frontend" / "src" / "features" / "landing" / "samples"
PROVENANCE = "Real Kestrix output on a synthetic input generated by scripts/build_landing_samples.py."

# --- Email ---------------------------------------------------------------------------------

EMAIL_FROM_NAME = "Northbank Billing"
EMAIL_FROM = "billing@n0rthbank-secure.example"
EMAIL_REPLY_TO = "accounts.northbank@payments-desk.example"
EMAIL_TO = "you@company.example"
EMAIL_SUBJECT = "URGENT: Updated bank details for invoice INV-20817"
EMAIL_LINK_TEXT = "www.northbank.example"
EMAIL_LINK_HREF = "http://pay.n0rthbank-secure.example/update-details"
EMAIL_ATTACHMENT = "invoice.pdf.exe"
EMAIL_PARAGRAPHS = (
    "Hello,",
    "Please note our bank details have changed. Update your payment details before you pay the "
    "attached invoice INV-20817.",
    "Payment is due today: please complete the wire transfer within 24 hours to avoid a late fee.",
    "Confirm the new account here:",
    "Kind regards, Accounts Team",
)


def build_email() -> bytes:
    msg = EmailMessage()
    msg["From"] = f'"{EMAIL_FROM_NAME}" <{EMAIL_FROM}>'
    msg["Reply-To"] = EMAIL_REPLY_TO
    msg["To"] = EMAIL_TO
    msg["Subject"] = EMAIL_SUBJECT
    msg["Date"] = "Mon, 05 Oct 2026 08:14:00 +0000"
    msg["Message-ID"] = "<inv-20817@n0rthbank-secure.example>"
    plain = "\n\n".join([*EMAIL_PARAGRAPHS[:3], f"{EMAIL_PARAGRAPHS[3]} {EMAIL_LINK_HREF}", EMAIL_PARAGRAPHS[4]])
    msg.set_content(plain)
    html = "".join(f"<p>{p}</p>" for p in EMAIL_PARAGRAPHS[:3])
    html += f'<p>{EMAIL_PARAGRAPHS[3]} <a href="{EMAIL_LINK_HREF}">{EMAIL_LINK_TEXT}</a></p>'
    html += f"<p>{EMAIL_PARAGRAPHS[4]}</p>"
    msg.add_alternative(html, subtype="html")
    program = b"MZ" + b"\x90\x00" * 31 + b"This program cannot be run in DOS mode." + bytes(64)
    msg.add_attachment(program, maintype="application", subtype="octet-stream", filename=EMAIL_ATTACHMENT)
    return msg.as_bytes()


def email_sample() -> dict[str, Any]:
    report = analyze_mail(build_email(), protected_domains=frozenset({"northbank.example"}))
    return {
        "provenance": PROVENANCE,
        "message": {
            "from_name": EMAIL_FROM_NAME,
            "from_address": EMAIL_FROM,
            "reply_to": EMAIL_REPLY_TO,
            "to": EMAIL_TO,
            "subject": EMAIL_SUBJECT,
            "date": "Mon, 5 Oct 2026, 08:14",
            "paragraphs": list(EMAIL_PARAGRAPHS),
            "link_text": EMAIL_LINK_TEXT,
            "link_href": EMAIL_LINK_HREF,
            "attachment": EMAIL_ATTACHMENT,
        },
        "protected_domains": ["northbank.example"],
        "report": {
            "verdict": report.verdict,
            "heuristic_score": report.heuristic_score,
            "notice": report.notice,
            "findings": [
                {
                    "id": f.id,
                    "analyzer": f.analyzer,
                    "severity": f.severity,
                    "title": f.title,
                    "evidence": f.evidence,
                }
                for f in report.findings
            ],
        },
    }


# --- Web check (throwaway local demo site) -------------------------------------------------

DEMO_PAGE = (
    b"<!doctype html><html><head><title>Northbank Demo Shop</title></head>"
    b"<body><h1>Northbank Demo Shop</h1><form method=post action=/login>"
    b"<input name=user><input name=password type=password><button>Sign in</button></form></body></html>"
)


class _WeakSite(BaseHTTPRequestHandler):
    server_version = "DemoServer/1.0"  # sent as the Server header, so the sample never shows the local Python
    sys_version = ""

    def do_GET(self) -> None:
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Set-Cookie", "session=demo123; Path=/")
        self.send_header("Content-Length", str(len(DEMO_PAGE)))
        self.end_headers()
        self.wfile.write(DEMO_PAGE)

    def log_message(self, format: str, *args: Any) -> None:
        return


def webcheck_sample() -> dict[str, Any]:
    server = ThreadingHTTPServer(("127.0.0.1", 0), _WeakSite)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        url = f"http://127.0.0.1:{server.server_address[1]}/"
        report = scan_site(url, allow_private=True, scope="page")  # the sample shows one page
    finally:
        server.shutdown()
        server.server_close()
    if not report.headers_checked:
        raise SystemExit("the local demo site did not answer; refusing to write a webcheck sample")
    return {
        "provenance": (
            "Real Kestrix output: a scan of a throwaway demo site served on 127.0.0.1 by "
            "scripts/build_landing_samples.py, with deliberately weak headers."
        ),
        "site_title": "Northbank Demo Shop",
        "status_code": report.status_code,
        "response_headers": {
            "Content-Type": "text/html; charset=utf-8",
            "Server": "DemoServer/1.0",
            "Set-Cookie": "session=demo123; Path=/",
        },
        "grade": report.grade,
        "score": report.score,
        "findings": [
            {
                "id": f.id,
                "severity": f.severity,
                "title": f.title,
                "recommendation": f.recommendation,
                "evidence": f.evidence,
            }
            for f in report.findings
        ],
    }


OFFLINE = {"email": email_sample}


def dump(data: dict[str, Any]) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    samples = {name: build() for name, build in OFFLINE.items()}
    samples["webcheck"] = webcheck_sample()
    for name, data in samples.items():
        (OUT / f"{name}.json").write_text(dump(data))
        print(f"wrote {OUT.relative_to(ROOT) / name}.json", file=sys.stderr)


if __name__ == "__main__":
    main()
