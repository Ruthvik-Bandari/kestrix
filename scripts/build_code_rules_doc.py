"""Regenerate the rules table in ``docs/modules/code.md`` from the rule registry.

Run from the repo root: ``uv run python scripts/build_code_rules_doc.py``. With ``--check`` it
writes nothing and exits 1 when the committed table differs from the registry;
``packages/kestrix-scan/tests/test_code_docs.py`` runs that check.

It also writes ``docs/modules/code-rules-provenance.md``, the per-rule clean-room notes (CWE entry,
cited documentation and the clean-room statement), and checks it the same way.
"""

from __future__ import annotations

import sys
from pathlib import Path

from kestrix_scan.registry import CLEAN_ROOM, RULES

DOC = Path(__file__).resolve().parents[1] / "docs" / "modules" / "code.md"
START = "<!-- rules:start (generated by scripts/build_code_rules_doc.py) -->"
END = "<!-- rules:end -->"
PROVENANCE = DOC.with_name("code-rules-provenance.md")


def rules_table() -> str:
    rows = [
        "| Rule id | Applies to | CWE | Severity | Confidence | What it finds |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for rule in RULES.values():
        scope = "Python" if rule.language == "python" else "any text file"
        rows.append(f"| `{rule.id}` | {scope} | {rule.cwe} | {rule.severity} | {rule.confidence} | {rule.title} |")
    return "\n".join(rows)


def render(document: str) -> str:
    head, start, rest = document.partition(START)
    _, end, tail = rest.partition(END)
    if not start or not end:
        raise SystemExit(f"{DOC} is missing the {START!r} / {END!r} markers")
    return f"{head}{START}\n{rules_table()}\n{END}{tail}"


def provenance() -> str:
    """The whole provenance page: one section per rule, in registry order."""
    parts = [
        "# Code rules: clean-room provenance",
        "",
        "<!-- generated by scripts/build_code_rules_doc.py from src/kestrix/code/rules.py; do not edit -->",
        "",
        "Each Kestrix code rule was written for Kestrix from its CWE entry and the language, library or "
        "standard documentation listed under it. No rule text, pattern or code from Semgrep, Snyk, CodeQL, "
        "Bandit, Trail of Bits or any other scanner was copied, ported or paraphrased. The rule table is in "
        "[code.md](code.md#rules).",
        "",
    ]
    for rule in RULES.values():
        parts += [f"## `{rule.id}`", "", f"- CWE: [{rule.cwe}]({rule.cwe_url})"]
        parts += [f"- Documentation: <{url}>" for url in rule.sources]
        parts += [f"- {CLEAN_ROOM}", ""]
    return "\n".join(parts)


def main() -> int:
    current = DOC.read_text(encoding="utf-8")
    updated = render(current)
    notes = provenance()
    stale = PROVENANCE.read_text(encoding="utf-8") if PROVENANCE.is_file() else None
    if "--check" in sys.argv[1:]:
        if updated != current or notes != stale:
            print(f"{DOC} or {PROVENANCE} is out of date; run scripts/build_code_rules_doc.py", file=sys.stderr)
            return 1
        return 0
    DOC.write_text(updated, encoding="utf-8")
    PROVENANCE.write_text(notes, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
