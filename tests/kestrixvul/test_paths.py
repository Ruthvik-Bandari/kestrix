import pytest

from kestrixvul.paths import content_reason, path_reason, size_reason


@pytest.mark.parametrize(
    ("path", "reason"),
    [
        ("src/app/views.py", None),
        ("lib/router.js", None),
        ("tests/test_views.py", "test"),
        ("pkg/views_test.py", "test"),
        ("src/__tests__/a.js", "test"),
        ("src/url.spec.ts", "test"),
        ("static/js/jquery.min.js", "minified"),
        ("node_modules/lodash/index.js", "vendored"),
        ("static/jquery-1.7.2.js", "vendored"),
        ("dist/app.js", "dist_or_bundle"),
        ("public/main.bundle.js", "dist_or_bundle"),
        ("app/migrations/0001_initial.py", "generated"),
        ("api/service_pb2.py", "generated"),
    ],
)
def test_path_reason(path: str, reason: str | None):
    assert path_reason(path) == reason


def test_content_reason_spots_minified_and_generated_files():
    assert content_reason("var a=1;" * 300) == "minified"
    assert content_reason("// Code generated by protoc. DO NOT EDIT.\nconst x = 1;\n") == "generated"
    assert content_reason("def f():\n    return 1\n") is None
    assert content_reason(None) is None
    assert content_reason("x = 1\n" * 400_000) == "oversized"


def test_size_reason_bounds_function_length():
    assert size_reason("def f(): pass") == "too_short"
    assert size_reason("def f():\n    x = 1\n    return x") is None
    assert size_reason("\n".join(["x = 1"] * 401)) == "too_long"
