"""File and function filters shared by ``qc`` and ``labels``.

A changed file is excluded from the candidate pool when it is a test, vendored, bundled/dist,
minified or generated file (``docs/research/code-vuln-ml-plan.md``: drop minified, bundled,
``vendor/`` and ``dist/`` JavaScript first). The rules are path patterns plus two content checks
(line-length statistics for minified code, and a generated-file banner in the first lines).
"""

from __future__ import annotations

import re

LANGUAGES = {"Python": "python", "JavaScript": "javascript", "TypeScript": "typescript"}
MIN_LINES = 3
MAX_LINES = 400
MAX_FILE_CHARS = 2_000_000  # larger "source" files are generated data or bundles, never hand-written modules

TEST_DIRS = {"test", "tests", "__tests__", "testing", "spec", "specs", "e2e", "__mocks__", "fixtures", "testdata"}
TEST_FILE = re.compile(
    r"^(test_.*\.py|.*_tests?\.py|conftest\.py|tests?\.py|.*\.(test|spec)\.[cm]?[jt]sx?|test\.[cm]?[jt]sx?)$"
)
VENDOR_DIRS = {
    "vendor",
    "vendors",
    "node_modules",
    "bower_components",
    "jspm_packages",
    "third_party",
    "thirdparty",
    "third-party",
    "3rdparty",
    "external",
    "externals",
    "site-packages",
}
# A JavaScript file named after a library and a version is a copied release, e.g. jquery-1.7.2.js.
VERSIONED_COPY = re.compile(r"^[a-z][\w.]*?[-.]v?\d+\.\d+(\.\d+)*([-.][\w.]+)?\.[cm]?js$", re.IGNORECASE)
DIST_DIRS = {"dist", "build", "_build", "bundle", "bundles", ".next", ".nuxt", "out", "compiled"}
DIST_FILE = re.compile(
    r"(\.bundle|\.chunk|-bundle|\.umd|\.prod|\.production)(\.[0-9a-f]{6,})?\.[cm]?js$|^bundle\.[cm]?js$"
)
MINIFIED_FILE = re.compile(r"[.-]min\.[cm]?[jt]s$")
GENERATED_FILE = re.compile(r"(_pb2(_grpc)?\.py|\.generated\.\w+|\.g\.[jt]s|\.d\.ts)$")
GENERATED_DIRS = {"migrations", "__generated__", "generated"}
GENERATED_BANNER = re.compile(
    r"(@generated|auto-?generated|do not edit|generated by (the )?(protoc|django|babel|webpack|tsc|rollup|esbuild|swagger|openapi))",
    re.IGNORECASE,
)


def path_reason(path: str) -> str | None:
    """Why a changed file is excluded by its path, or None to keep it."""
    parts = [p for p in path.replace("\\", "/").split("/") if p]
    if not parts:
        return "no_path"
    name = parts[-1]
    dirs = [p.lower() for p in parts[:-1]]
    lowered = name.lower()
    if MINIFIED_FILE.search(lowered):
        return "minified"
    if any(d in VENDOR_DIRS for d in dirs) or (lowered.endswith(("js", "ts")) and VERSIONED_COPY.match(lowered)):
        return "vendored"
    if any(d in DIST_DIRS for d in dirs) or DIST_FILE.search(lowered):
        return "dist_or_bundle"
    if any(d in GENERATED_DIRS for d in dirs) or GENERATED_FILE.search(lowered):
        return "generated"
    if any(d in TEST_DIRS for d in dirs) or TEST_FILE.match(lowered):
        return "test"
    return None


def looks_minified(code: str) -> bool:
    """Very long lines, or long code with a high average line length."""
    lines = code.splitlines() or [""]
    longest = max(len(line) for line in lines)
    average = len(code) / len(lines)
    return longest > 1000 or (len(code) > 1000 and average > 200)


def generated_banner(code: str) -> bool:
    head = "\n".join(code.splitlines()[:5])
    return bool(GENERATED_BANNER.search(head))


def content_reason(file_code: str | None) -> str | None:
    """Exclusion reason from the whole file's text (oversized, minified or generated), if any."""
    if not file_code:
        return None
    if len(file_code) > MAX_FILE_CHARS:
        return "oversized"
    if looks_minified(file_code):
        return "minified"
    if generated_banner(file_code):
        return "generated"
    return None


def size_reason(code: str) -> str | None:
    lines = code.strip("\n").splitlines()
    if len(lines) < MIN_LINES:
        return "too_short"
    if len(lines) > MAX_LINES:
        return "too_long"
    return None
